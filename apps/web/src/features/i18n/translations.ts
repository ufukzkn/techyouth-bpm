export type TranslationKey = keyof typeof translations.tr;

export function translate(language: Language, key: TranslationKey, values?: Record<string, string | number>) {
  let template = translations[language][key] ?? translations[defaultLanguage][key] ?? key;

  if (!values) {
    return template;
  }

  for (const [name, value] of Object.entries(values)) {
    template = template.replaceAll(`{${name}}`, String(value));
  }

  return template;
}

export function statusLabel(language: Language, status: ProcessStatus) {
  return translate(language, `status.${status}` as TranslationKey);
}

export function actionLabel(language: Language, action: Exclude<WorkflowAction, "Start">) {
  return translate(language, `action.${action}` as TranslationKey);
}
